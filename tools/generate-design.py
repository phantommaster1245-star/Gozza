from pathlib import Path
import json
r=Path(__file__).resolve().parents[1]
t=json.loads((r/'design/tokens.json').read_text())
colors=t['colors']
res=r/'gps/src/main/res/values'
(res/'gozza_tokens.xml').write_text('<resources>\n'+''.join(f' <color name="gozza_{k}">#{v}</color>\n' for k,v in colors.items())+''.join(f' <dimen name="gozza_text_{k}">{v}sp</dimen>\n' for k,v in t['typography'].items())+'</resources>\n',encoding='utf-8')
java=r/'shared/src/main/java/com/fulllock/app/GozzaDesign.java'
java.write_text('package com.fulllock.app;\n/** Generated by tools/generate-design.py from design/tokens.json. */\npublic final class GozzaDesign {\n'+''.join(f' public static final int {k}=0xFF{v};\n' for k,v in colors.items())+''.join(f' public static final int text_{k}={v};\n' for k,v in t['typography'].items())+' private GozzaDesign(){}\n}\n',encoding='utf-8')
